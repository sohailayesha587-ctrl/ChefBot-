const migrate = async () => {
  try {
    await mongoose.connect(process.env.MONGO_URI);
    console.log('MongoDB connected');

    const admin = await User.findOne({ email: 'chefbot.ai.kitchen@gmail.com' });
    if (!admin) {
      console.error('Admin not found');
      process.exit(1);
    }

    const validGuides = allGuides.filter(g => g.title && g.content);
    if (validGuides.length === 0) {
      console.log('No guides to insert');
      process.exit(0);
    }

    const toInsert = validGuides.map(g => ({ ...g, createdBy: admin._id }));
    const result = await BeginnersGuide.insertMany(toInsert);
    console.log(`${result.length} guides inserted`);
    process.exit(0);
  } catch (error) {
    console.error('Migration failed:', error);
    process.exit(1);
  }
};

migrate();